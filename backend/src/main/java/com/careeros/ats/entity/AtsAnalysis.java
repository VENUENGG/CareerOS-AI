package com.careeros.ats.entity;

import com.careeros.resume.entity.Resume;
import jakarta.persistence.CollectionTable;
import jakarta.persistence.Column;
import jakarta.persistence.ElementCollection;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OrderColumn;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.Setter;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;

@Entity
@Table(name = "ats_analyses")
@Getter
@Setter
public class AtsAnalysis {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /*
     * One resume can have multiple ATS analyses.
     *
     * This intentionally uses ManyToOne so we can preserve
     * analysis history instead of overwriting previous results.
     */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(
            name = "resume_id",
            nullable = false
    )
    private Resume resume;

    /*
     * GENERAL:
     * Resume quality without a target job.
     *
     * JOB_SPECIFIC:
     * Resume evaluated against a specific job description.
     */
    @Enumerated(EnumType.STRING)
    @Column(
            name = "analysis_type",
            nullable = false,
            length = 30
    )
    private AtsAnalysisType analysisType;

    /*
     * Scores are percentages from 0 to 100.
     *
     * Validation of the actual values is handled by the service layer
     * because these fields are generated by the ATS engine rather
     * than received directly from an API request.
     */
    @Column(name = "ats_score")
    private Integer atsScore;

    @Column(name = "keyword_score")
    private Integer keywordScore;

    @Column(name = "skills_score")
    private Integer skillsScore;

    @Column(name = "experience_score")
    private Integer experienceScore;

    @Column(name = "education_score")
    private Integer educationScore;

    @Column(name = "formatting_score")
    private Integer formattingScore;

    /*
     * Target job information.
     *
     * These are populated for JOB_SPECIFIC analyses.
     * They remain null for GENERAL analyses.
     */
    @Column(
            name = "job_title",
            columnDefinition = "TEXT"
    )
    private String jobTitle;

    @Column(
            name = "job_description",
            columnDefinition = "TEXT"
    )
    private String jobDescription;

    /*
     * Keywords found in both the resume and target job.
     */
    @ElementCollection
    @CollectionTable(
            name = "ats_matched_keywords",
            joinColumns = @JoinColumn(name = "ats_analysis_id")
    )
    @OrderColumn(name = "keyword_order")
    @Column(
            name = "keyword",
            nullable = false
    )
    private List<String> matchedKeywords = new ArrayList<>();

    /*
     * Relevant job keywords that were not found
     * in the resume.
     */
    @ElementCollection
    @CollectionTable(
            name = "ats_missing_keywords",
            joinColumns = @JoinColumn(name = "ats_analysis_id")
    )
    @OrderColumn(name = "keyword_order")
    @Column(
            name = "keyword",
            nullable = false
    )
    private List<String> missingKeywords = new ArrayList<>();

    /*
     * Positive findings identified by the ATS engine.
     */
    @ElementCollection
    @CollectionTable(
            name = "ats_strengths",
            joinColumns = @JoinColumn(name = "ats_analysis_id")
    )
    @OrderColumn(name = "strength_order")
    @Column(
            name = "strength",
            nullable = false,
            columnDefinition = "TEXT"
    )
    private List<String> strengths = new ArrayList<>();

    /*
     * Problems detected in the resume.
     */
    @ElementCollection
    @CollectionTable(
            name = "ats_weaknesses",
            joinColumns = @JoinColumn(name = "ats_analysis_id")
    )
    @OrderColumn(name = "weakness_order")
    @Column(
            name = "weakness",
            nullable = false,
            columnDefinition = "TEXT"
    )
    private List<String> weaknesses = new ArrayList<>();

    /*
     * Recommended improvements.
     */
    @ElementCollection
    @CollectionTable(
            name = "ats_suggestions",
            joinColumns = @JoinColumn(name = "ats_analysis_id")
    )
    @OrderColumn(name = "suggestion_order")
    @Column(
            name = "suggestion",
            nullable = false,
            columnDefinition = "TEXT"
    )
    private List<String> suggestions = new ArrayList<>();

    /*
     * Audit timestamps.
     */
    @CreationTimestamp
    @Column(
            name = "created_at",
            nullable = false,
            updatable = false
    )
    private LocalDateTime createdAt;

    @UpdateTimestamp
    @Column(
            name = "updated_at",
            nullable = false
    )
    private LocalDateTime updatedAt;
}